import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tokens } from '../../../packages/shared/dist/design-tokens.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, '..', 'miniprogram', 'styles', 'tokens.wxss');

function flat(prefix, obj) {
  const lines = [];
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === 'string') {
      lines.push(`  --${prefix}${k}: ${v};`);
    } else {
      lines.push(...flat(`${prefix}${k}-`, v));
    }
  }
  return lines;
}

const light = flat('', {
  paper: tokens.paper,
  ink: tokens.ink,
  kraft: tokens.kraft,
  pin: tokens.pin,
  shadow: tokens.shadow,
});
const dark = flat('', {
  paper: tokens.dark.paper,
  ink: tokens.dark.ink,
  kraft: tokens.dark.kraft,
  pin: tokens.dark.pin,
  shadow: tokens.shadow,
});

/**
 * Font-family CSS variables. Kept here (not in shared/design-tokens.ts)
 * because the mini-program has different available system fonts than the
 * browser; the web side picks fonts via Tailwind utilities.
 *
 *   --font-hand  Used for headings + photo captions. The Latin fallback
 *                Caveat is unlikely to exist on Android, so we lead with
 *                Chinese kaiti faces (STKaiti on iOS, Kaiti SC on macOS
 *                simulator, AaKaiSong/Hiragino fallback on other Android)
 *                and let the cursive stack catch Latin glyphs.
 *
 *   --font-mono  Small uppercase labels (TIMELINE · 1 ENTRIES, date in
 *                rail, etc). Mini-program inherits system mono fonts.
 */
const fontVars = [
  '  --font-hand: "STKaiti", "Kaiti SC", "FZShuTi", "HiraMinProN-W3", "Caveat", "Brush Script MT", cursive;',
  '  --font-mono: "JetBrains Mono", "Menlo", "Consolas", "Courier New", monospace;',
  '  --font-serif: "Source Han Serif SC", "Songti SC", "Times New Roman", serif;',
];

const out = [
  '/* AUTO-GENERATED by scripts/generate-tokens-wxss.mjs. Do not edit. */',
  'page {',
  ...light,
  ...fontVars,
  '}',
  '.dark, page.dark {',
  ...dark,
  '}',
  '',
].join('\n');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out, 'utf8');
console.log(`wrote ${OUT} (${out.length} bytes)`);
